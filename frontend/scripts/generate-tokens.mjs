/**
 * Reads ../design/tokens.json (DTCG single source of truth) and generates:
 *   - src/design/tokens.css
 *   - src/design/tokens.ts
 *   - src/design/tailwind.theme.json
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const FRONTEND_DIR = path.resolve(__dirname, "..");
const REPO_ROOT = path.resolve(FRONTEND_DIR, "..");
const TOKENS_PATH = path.join(REPO_ROOT, "design", "tokens.json");
const OUT_DIR = path.join(FRONTEND_DIR, "src", "design");

const raw = JSON.parse(fs.readFileSync(TOKENS_PATH, "utf8"));
const REF_RE = /^\{([^}]+)\}$/;

function lookup(dotPath) {
  let node = raw;
  for (const part of dotPath.split(".")) {
    if (!(part in node)) {
      throw new Error(`Unresolved token reference: ${dotPath}`);
    }
    node = node[part];
  }
  return typeof node === "object" && node !== null && "$value" in node ? node.$value : node;
}

function resolveValue(val) {
  if (typeof val === "string") {
    const match = REF_RE.exec(val);
    if (match) {
      return resolveValue(lookup(match[1]));
    }
  }
  return val;
}

function toCssVarName(prefix, key) {
  return `--${prefix}-${key.replace(/\./g, "-")}`;
}

function formatCssValue(val, type) {
  if (type === "fontFamily" && Array.isArray(val)) {
    return val.map((f) => (f.includes(" ") ? `"${f}"` : f)).join(", ");
  }
  if (type === "cubicBezier" && Array.isArray(val)) {
    return `cubic-bezier(${val.join(", ")})`;
  }
  return String(val);
}

// 1. Resolve primitives
const primitiveVars = {};
const primitiveValues = {};
for (const [group, entries] of Object.entries(raw.primitive)) {
  if (group === "color") continue; // Primitives colors stay internal; UI uses semantic tokens only.
  primitiveValues[group] = {};
  for (const [key, token] of Object.entries(entries)) {
    const resolved = resolveValue(token.$value);
    const cssVal = formatCssValue(resolved, token.$type);
    primitiveValues[group][key] = cssVal;
    primitiveVars[toCssVarName(group, key)] = cssVal;
  }
}

// 2. Resolve semantic tokens for dark & light
const semanticThemes = {};
for (const themeName of ["dark", "light"]) {
  semanticThemes[themeName] = {};
  for (const [key, token] of Object.entries(raw.semantic[themeName])) {
    semanticThemes[themeName][key] = String(resolveValue(token.$value));
  }
}

// 3. Resolve component tokens
const componentVars = {};
const componentValues = {};
for (const [comp, props] of Object.entries(raw.component)) {
  componentValues[comp] = {};
  for (const [prop, val] of Object.entries(props)) {
    const resolved = String(resolveValue(val));
    componentValues[comp][prop] = resolved;
    componentVars[`--component-${comp}-${prop}`] = resolved;
  }
}

// 4. Generate src/design/tokens.css
const cssLines = [
  "/* AUTO-GENERATED by `npm run tokens` from design/tokens.json. Do not edit by hand. */",
  "",
  ":root {",
  ...Object.entries(primitiveVars).map(([k, v]) => `  ${k}: ${v};`),
  ...Object.entries(componentVars).map(([k, v]) => `  ${k}: ${v};`),
  "  --surface-highlight: rgba(255, 255, 255, 0.06);",
  "  --text-on-accent: #05070D;",
  ...Object.entries(semanticThemes.dark).map(([k, v]) => `  --${k.replace(/\./g, "-")}: ${v};`),
  "}",
  "",
  '[data-theme="dark"] {',
  "  color-scheme: dark;",
  "  --surface-highlight: rgba(255, 255, 255, 0.06);",
  "  --text-on-accent: #05070D;",
  ...Object.entries(semanticThemes.dark).map(([k, v]) => `  --${k.replace(/\./g, "-")}: ${v};`),
  "}",
  "",
  '[data-theme="light"] {',
  "  color-scheme: light;",
  "  --surface-highlight: rgba(255, 255, 255, 0.72);",
  "  --text-on-accent: #FFFFFF;",
  ...Object.entries(semanticThemes.light).map(([k, v]) => `  --${k.replace(/\./g, "-")}: ${v};`),
  "}",
  "",
];

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.writeFileSync(path.join(OUT_DIR, "tokens.css"), cssLines.join("\n"), "utf8");

// 5. Generate src/design/tokens.ts
const semanticVarMap = Object.fromEntries(
  Object.keys(semanticThemes.dark).map((k) => [k, `var(--${k.replace(/\./g, "-")})`]),
);

const tsContent = `/* AUTO-GENERATED by \`npm run tokens\` from design/tokens.json. Do not edit by hand. */

export const semanticTokens = ${JSON.stringify(semanticThemes, null, 2)} as const;

export const semanticVars = ${JSON.stringify(semanticVarMap, null, 2)} as const;

export const componentTokens = ${JSON.stringify(componentValues, null, 2)} as const;

export const spaceTokens = ${JSON.stringify(primitiveValues.space, null, 2)} as const;

export const radiusTokens = ${JSON.stringify(primitiveValues.radius, null, 2)} as const;

export const sizeTokens = ${JSON.stringify(primitiveValues.size, null, 2)} as const;

export const durationTokens = ${JSON.stringify(primitiveValues.duration, null, 2)} as const;

export type SemanticTokenKey = keyof typeof semanticVars;
export type ThemeMode = "system" | "dark" | "light";
export type ResolvedTheme = "dark" | "light";
`;

fs.writeFileSync(path.join(OUT_DIR, "tokens.ts"), tsContent, "utf8");

// 6. Generate src/design/tailwind.theme.json (strictly mapped to CSS variables)
const twColors = {
  transparent: "transparent",
  current: "currentColor",
  "text-on-accent": "var(--text-on-accent)",
};
for (const key of Object.keys(semanticThemes.dark)) {
  const flat = key.replace(/\./g, "-");
  twColors[flat] = `var(--${flat})`;
}

const twSpacing = {};
for (const key of Object.keys(primitiveValues.space)) {
  twSpacing[key] = `var(--space-${key})`;
}
twSpacing["topbar"] = "var(--component-topbar-height)";
twSpacing["sidebar"] = "var(--component-sidebar-width)";
twSpacing["sidebar-collapsed"] = "var(--component-sidebar-width-collapsed)";
twSpacing["btn-sm"] = "var(--component-button-height-sm)";
twSpacing["btn-md"] = "var(--component-button-height-md)";
twSpacing["btn-lg"] = "var(--component-button-height-lg)";
twSpacing["ring-hero"] = "var(--component-ring-size-hero)";

const twRadius = {};
for (const key of Object.keys(primitiveValues.radius)) {
  twRadius[key] = `var(--radius-${key})`;
}

const twFonts = {};
for (const key of Object.keys(primitiveValues.font)) {
  twFonts[key] = `var(--font-${key})`;
}

const twFontSize = {};
for (const key of Object.keys(primitiveValues.size)) {
  twFontSize[key] = `var(--size-${key})`;
}

const twDuration = {};
for (const key of Object.keys(primitiveValues.duration)) {
  twDuration[key] = `var(--duration-${key})`;
}

const twEasing = {
  out: "var(--easing-out)",
  "in-out": "var(--easing-inOut)",
};

const twShadow = {
  none: "none",
  "glow-accent": "var(--component-glow-accent)",
  "glow-danger": "var(--component-glow-danger)",
};

const tailwindTheme = {
  colors: twColors,
  spacing: twSpacing,
  borderRadius: twRadius,
  fontFamily: twFonts,
  fontSize: twFontSize,
  transitionDuration: twDuration,
  transitionTimingFunction: twEasing,
  boxShadow: twShadow,
};

fs.writeFileSync(
  path.join(OUT_DIR, "tailwind.theme.json"),
  JSON.stringify(tailwindTheme, null, 2) + "\n",
  "utf8",
);

console.log("Generated src/design/tokens.css, src/design/tokens.ts, and src/design/tailwind.theme.json");
