export function parseScenarioParam(search: string): ScenarioName {
  const params = new URLSearchParams(search);
  const value = params.get("scenario") as ScenarioName | null;
  if (value && value in SCENARIO_FIXTURES) {
    return value;
  }
  return "idle";
}
